# 四大零件都在里面，找找看：
#   变量 = 记数据（仓库）
#   函数 = 复盘按钮（投进去股票，掉出来一段话）
#   判断 = 涨跌门卫（走哪条路）
#   循环 = 对每只股票来一遍
#
# 说明：Python 允许用中文给变量和函数起名，
# 今天故意全用中文，让你每一行都读得懂。
