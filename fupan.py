# 【变量】今天的模拟行情：一个清单，每只股票一张卡片
# （卡片上记着：名字、涨跌幅）
股票清单 = [
    {"名字": "贵州茅台", "涨跌幅": 0},
    {"名字": "宁德时代", "涨跌幅": -1.2},
    {"名字": "腾讯控股", "涨跌幅": 0.8},
    {"名字": "中芯国际", "涨跌幅": -3.1},
]

# 【函数】复盘按钮：投进去一张股票卡片，掉出来一句复盘话
def 复盘(股票):
    if 股票["涨跌幅"] >= 0:          # 【判断】门卫问：涨跌幅 >= 0 吗？
        语气 = "强势，可继续观察持有"   # 是 → 走这条路
    else:
        语气 = "走弱，注意风险别急加仓"  # 否 → 走这条路
    return f"{股票['名字']} 今日 {股票['涨跌幅']}%，{语气}"

# 【循环】对清单里的每一只股票：按一次复盘按钮，把结果打出来
print("=== 今日复盘 ===")
for 股票 in 股票清单:
    print(复盘(股票))               # 按按钮：投进去"股票"，掉出来一句话
print("=== 复盘完成，共", len(股票清单), "只 ===")
